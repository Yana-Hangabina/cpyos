#!/usr/bin/env python3
"""Inline the shared CPYOS web pages into a C++ include for the Plus server.

The shared FilesPage.html is a template with `<!--#include file="../shared/...">`
directives. The port serves the resolved page from flash, so this script expands
the includes and emits a header with a raw string literal per language.

    python3 scripts/gen_web_pages.py --out build/web_pages.inc
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
PORT = HERE.parent
REPO = PORT.parents[1]
HTML = REPO / "src" / "network" / "html"
INCLUDE = re.compile(r'<!--#include file="([^"]+)"\s*-->')

PAGES = (("en", "FilesPage.html", "kFilesPageEn"), ("zh-CN", "FilesPage.html", "kFilesPageZh"),
         ("en", "FontsPage.html", "kFontsPageEn"), ("zh-CN", "FontsPage.html", "kFontsPageZh"),
         ("en", "HomePage.html", "kHomePageEn"), ("zh-CN", "HomePage.html", "kHomePageZh"))


def expand(path: Path) -> str:
    text = path.read_text(encoding="utf-8")

    def repl(match: re.Match[str]) -> str:
        target = (path.parent / match.group(1)).resolve()
        return expand(target)

    text = INCLUDE.sub(repl, text)
    # Teach the shared page about this panel so "auto" image conversion uses the
    # real 1216x684 target instead of falling back to the X4 profile.
    text = text.replace("const DEVICE_PROFILES = {",
                        "const DEVICE_PROFILES = {\n  PLUS: { width: 1216, height: 684, label: 'Metalio Plus' },")
    text = text.replace("const STATUS_DEVICE_MAP = {",
                        "const STATUS_DEVICE_MAP = {\n  cpyos_metalio_plus: 'PLUS',")
    return text


def literal(name: str, text: str) -> str:
    "Emit the page as a gzip blob: the browser decompresses it, the device keeps\n    # only ~5x smaller bytes in flash (the pages are mostly inline JS/CSS)."
    import gzip

    data = gzip.compress(text.encode("utf-8"), compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(data), 24):
        lines.append(",".join(str(b) for b in data[i:i + 24]))
    body = ",\n  ".join(lines)
    return (f"static const unsigned char {name}[] = {{\n  {body}\n}};\n"
            f"static const unsigned int {name}Len = {len(data)};\n")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    chunks = ["// Generated by ports/metalio_plus/scripts/gen_web_pages.py; do not edit.\n",
              "#pragma once\n"]
    for language, filename, symbol in PAGES:
        source = HTML / language / filename
        if not source.is_file():
            raise SystemExit(f"missing {source}")
        chunks.append(literal(symbol, expand(source)))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("".join(chunks), encoding="utf-8")
    print(f"wrote {args.out} ({args.out.stat().st_size:,} B)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())