#!/usr/bin/env python3
"""Inventory a kiikoread checkout for the Metalio E-INK4 Plus port.

The port deliberately copies no kiikoread file: the Plus board package and the
shared `KIIKO_BOARD_METALIO47` branches are used only as a behavioural and
licensing reference. This script makes that claim auditable from a local
checkout (it never downloads anything):

* counts the files in `boards/metalio47` and `components/metalio_hw`;
* classifies the SPDX header of each file (Apache-2.0, Personal-Study, MIT,
  other, none);
* lists every file whose header names `LicenseRef-Kiikoread-Personal-Study-1.0`
  (those must never be copied into CPYOS);
* counts shared files that mention `KIIKO_BOARD_METALIO47`, grouped by top-level
  directory, so the "111 shared files" claim in the engineering doc can be
  re-checked.

Usage:
    python3 scripts/inventory_kiikoread.py --tree /path/to/read-pico-reader
    python3 scripts/inventory_kiikoread.py --tree ... --json
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from collections import Counter
from pathlib import Path

SPDX_RE = re.compile(r"SPDX-License-Identifier:\s*([^\s*]+)")
BRANCH_MARK = "KIIKO_BOARD_METALIO47"
LICENSE_NAMES = {
    "Apache-2.0": "Apache-2.0",
    "LicenseRef-Kiikoread-Personal-Study-1.0": "Personal-Study",
    "MIT": "MIT",
}


def classify(path: Path) -> str:
    head = path.read_bytes()[:4096].decode("utf-8", "replace")
    match = SPDX_RE.search(head)
    if not match:
        return "none"
    spdx = match.group(1).rstrip(",;")
    return LICENSE_NAMES.get(spdx, spdx if spdx else "none")


def scan_dir(root: Path) -> dict:
    files = sorted(p for p in root.rglob("*") if p.is_file())
    counts = Counter()
    personal: list[str] = []
    entries = []
    for path in files:
        license_name = classify(path)
        counts[license_name] += 1
        rel = path.relative_to(root).as_posix()
        if license_name == "Personal-Study":
            personal.append(rel)
        entries.append({"path": rel, "license": license_name, "bytes": path.stat().st_size})
    return {"files": len(files), "licenses": dict(sorted(counts.items())),
            "personal_study": personal, "entries": entries}


def tree_head(tree: Path) -> str:
    try:
        result = subprocess.run(["git", "-C", str(tree), "describe", "--tags", "--always"],
                                capture_output=True, text=True, check=False)
        return result.stdout.strip() or "unknown"
    except OSError:
        return "unknown"


def write_markdown(report: dict, tree: Path, out: Path) -> None:
    lines = [
        "# kiikoread rc110 file inventory",
        "",
        f"Generated by `ports/metalio_plus/scripts/inventory_kiikoread.py` from a local"
        f" `{tree.name}` checkout (HEAD `{tree_head(tree)}`).",
        "Licenses come from each file's SPDX header; `none` means no header in the first 4 KiB.",
        "",
        f"## boards/metalio47 ({report['boards_metalio47']['files']} files)",
        "",
        "| file | license | bytes |",
        "|---|---|---:|",
    ]
    for entry in report["boards_metalio47"]["entries"]:
        lines.append(f"| `{entry['path']}` | {entry['license']} | {entry['bytes']:,} |")
    lines += [
        "",
        f"## components/metalio_hw ({report['components_metalio_hw']['files']} files)",
        "",
        "| file | license | bytes |",
        "|---|---|---:|",
    ]
    for entry in report["components_metalio_hw"]["entries"]:
        lines.append(f"| `{entry['path']}` | {entry['license']} | {entry['bytes']:,} |")
    shared = report["shared_branch"]
    lines += [
        "",
        f"## Shared code files mentioning `{BRANCH_MARK}` ({shared['code_files']})",
        "",
        "| file | license | bytes |",
        "|---|---|---:|",
    ]
    for entry in shared["code_list"]:
        lines.append(f"| `{entry['path']}` | {entry['license']} | {entry['bytes']:,} |")
    lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8")


CODE_SUFFIXES = {".c", ".h", ".cc", ".cpp", ".hpp"}


def scan_shared(tree: Path) -> dict:
    code: Counter = Counter()
    other: Counter = Counter()
    code_files: list[dict] = []
    for path in tree.rglob("*"):
        if not path.is_file() or path.suffix not in (CODE_SUFFIXES | {".py", ".txt", ".cmake"}):
            continue
        try:
            text = path.read_bytes().decode("utf-8", "replace")
        except OSError:
            continue
        if BRANCH_MARK not in text:
            continue
        rel = path.relative_to(tree)
        top = rel.parts[0] if rel.parts else "."
        is_code = path.suffix in CODE_SUFFIXES
        (code if is_code else other)[top] += 1
        if is_code:
            code_files.append({"path": rel.as_posix(), "license": classify(path),
                               "bytes": path.stat().st_size})
    return {
        "code_files": sum(code.values()),
        "code_by_top_level": dict(sorted(code.items())),
        "other_files": sum(other.values()),
        "other_by_top_level": dict(sorted(other.items())),
        "code_list": sorted(code_files, key=lambda item: item["path"]),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tree", type=Path, required=True, help="kiikoread checkout root")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--markdown", type=Path, help="write the full per-file inventory table")
    args = parser.parse_args()

    tree = args.tree.resolve()
    for required in ("boards/metalio47", "components/metalio_hw"):
        if not (tree / required).is_dir():
            raise SystemExit(f"{tree}: missing {required}")

    report = {
        "tree": str(tree),
        "boards_metalio47": scan_dir(tree / "boards" / "metalio47"),
        "components_metalio_hw": scan_dir(tree / "components" / "metalio_hw"),
        "shared_branch": scan_shared(tree),
    }
    if args.markdown:
        args.markdown.parent.mkdir(parents=True, exist_ok=True)
        write_markdown(report, tree, args.markdown)
        print(f"wrote {args.markdown}")
    if args.json:
        print(json.dumps(report, indent=2, sort_keys=True))
        return 0

    for label in ("boards_metalio47", "components_metalio_hw"):
        entry = report[label]
        print(f"{label}: {entry['files']} files")
        for name, count in entry["licenses"].items():
            print(f"  {count:4d}  {name}")
        if entry["personal_study"]:
            print("  Personal-Study files (do not copy):")
            for name in entry["personal_study"]:
                print(f"    {name}")
    shared = report["shared_branch"]
    print(f"shared code files mentioning {BRANCH_MARK}: {shared['code_files']}")
    for top, count in shared["code_by_top_level"].items():
        print(f"  {count:4d}  {top}/")
    print(f"shared non-code files (py/txt/cmake): {shared['other_files']}")
    for top, count in shared["other_by_top_level"].items():
        print(f"  {count:4d}  {top}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
