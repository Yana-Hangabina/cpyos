import os
import sys

# SCons executes pre-scripts without defining __file__, and sys.path[0] is not
# guaranteed to be this directory; make `import web_assets` work in both the
# build and a manual `python3 scripts/build_html.py` from the repo root.
_HERE = os.path.dirname(os.path.abspath(globals().get("__file__", os.path.join("scripts", "build_html.py"))))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)

import web_assets  # noqa: E402  (path setup above)

SRC_DIR = "src"
HTML_EXT = ".html"
JS_EXT = ".js"
HEADER_PREAMBLE = "// THIS FILE IS AUTOGENERATED, DO NOT EDIT MANUALLY\n\n"
HEADER_PRAGMA = "#pragma once\n"
HEADER_INCLUDE = "#include <cstddef>\n\n"


def write_header(header_path: str, base_name: str, compressed: bytes, original_size: int) -> None:
    with open(header_path, "w", encoding="utf-8") as h:
        h.write(HEADER_PREAMBLE)
        h.write(HEADER_PRAGMA)
        h.write(HEADER_INCLUDE)

        # Write the compressed data as a byte array
        h.write(f"constexpr char {base_name}[] PROGMEM = {{\n")

        # Write bytes in rows of 16
        for i in range(0, len(compressed), 16):
            chunk = compressed[i:i+16]
            hex_values = ', '.join(f'0x{b:02x}' for b in chunk)
            h.write(f"  {hex_values},\n")

        h.write("};\n\n")
        h.write(f"constexpr size_t {base_name}CompressedSize = {len(compressed)};\n")
        h.write(f"constexpr size_t {base_name}OriginalSize = {original_size};\n")

        # ETag derived from the compressed payload. The content is immutable at
        # runtime (baked into flash at build time), so a strong ETag keyed on the
        # bytes is safe and stable. Browsers echo it back as If-None-Match,
        # enabling 304 responses.
        h.write(f'constexpr const char* {base_name}ETag = "\\"{web_assets.etag_for(compressed)}\\"";\n')


for root, _, files in os.walk(SRC_DIR):
    for file in files:
        if file.endswith((HTML_EXT, JS_EXT)):
            file_path = os.path.join(root, file)

            # Only minify HTML files; JS files are typically pre-minified (e.g., jszip.min.js).
            # The compression itself lives in web_assets so build_web_pack.py packs the very
            # same bytes for Read Pico's data-partition pack.
            is_html = file.endswith(HTML_EXT)
            compressed, processed_size = web_assets.compress_source(file_path, "html" if is_html else "js")

            # Create valid C identifier from filename
            # Use appropriate suffix based on file type
            base_name = web_assets.header_symbol(file_path)
            header_path = os.path.join(root, f"{base_name}.generated.h")
            write_header(header_path, base_name, compressed, processed_size)

            with open(file_path, "r", encoding="utf-8") as f:
                content_size = len(f.read())

            print(f"Generated: {header_path}")
            print(f"  Original: {content_size} bytes")
            print(f"  Minified: {processed_size} bytes ({100*processed_size/content_size:.1f}%)")
            print(f"  Compressed: {len(compressed)} bytes ({100*len(compressed)/content_size:.1f}%)")
