"""The bundled emoji subset keeps its slot budget and user-visible coverage.

`src/EmojiFont.cpp` reads an EMJ1 blob from the data partition; the blob is a
32-byte header plus `assets/emoji/NotoEmoji-subset.ttf`. The slot is fixed at
128 KiB, so adding glyphs means dropping others. This test pins the codepoints
users actually see in Wi-Fi SSIDs / titles / comments and the pack header.
"""

import struct
import sys
import unittest
import zlib
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parents[1]
ROOT = SCRIPTS.parent

TTF = ROOT / 'assets' / 'emoji' / 'NotoEmoji-subset.ttf'
PACK = ROOT / 'build' / 'emoji.dat'
MAX_TTF_BYTES = 0x20000 - 32

# Covered by the original subset (regression pins).
HISTORIC = [0x1F600, 0x1F34E, 0x2764, 0x2B50]
# Added for SSIDs/names: home, network, devices, locks, animals, popular faces.
REQUIRED = [
    0x1F3E0, 0x1F4F6, 0x1F310, 0x1F4E1, 0x1F4BB, 0x1F4F1, 0x1F5A5,
    0x1F512, 0x1F511, 0x26A1, 0x1F431, 0x1F436, 0x1F4A1, 0x1F319,
    0x1F914, 0x1F970, 0x1F929, 0x1F917, 0x1F97A, 0x1F697, 0x1F6B2,
]


def cmap_codepoints(data):
    """Minimal sfnt cmap reader (formats 4 and 12), no fontTools dependency."""
    num_tables = struct.unpack_from('>H', data, 4)[0]
    cmap_off = None
    for i in range(num_tables):
        tag, _checksum, offset, _length = struct.unpack_from('>4sIII', data, 12 + i * 16)
        if tag == b'cmap':
            cmap_off = offset
            break
    if cmap_off is None:
        raise AssertionError('no cmap table')
    _version, count = struct.unpack_from('>HH', data, cmap_off)
    subtables = []
    for i in range(count):
        platform, encoding, offset = struct.unpack_from('>HHI', data, cmap_off + 4 + i * 8)
        subtables.append((platform, encoding, cmap_off + offset))
    codepoints = set()
    for _platform, _encoding, off in subtables:
        fmt = struct.unpack_from('>H', data, off)[0]
        if fmt == 4:
            segx2 = struct.unpack_from('>H', data, off + 6)[0]
            seg = segx2 // 2
            ends = struct.unpack_from('>%dH' % seg, data, off + 14)
            starts = struct.unpack_from('>%dH' % seg, data, off + 16 + segx2)
            for start, end in zip(starts, ends):
                if 0xFFFF in (start, end):
                    continue
                codepoints.update(range(start, end + 1))
        elif fmt == 12:
            groups = struct.unpack_from('>I', data, off + 12)[0]
            for g in range(groups):
                start, end, _gid = struct.unpack_from('>III', data, off + 16 + g * 12)
                codepoints.update(range(start, end + 1))
    return codepoints


class EmojiPackTest(unittest.TestCase):
    def test_subset_fits_the_partition_slot(self):
        size = TTF.stat().st_size
        self.assertLessEqual(size, MAX_TTF_BYTES)
        self.assertGreater(size, 64 * 1024)

    def test_user_visible_codepoints_are_covered(self):
        covered = cmap_codepoints(TTF.read_bytes())
        missing = [cp for cp in HISTORIC + REQUIRED if cp not in covered]
        self.assertFalse(missing, 'missing emoji: ' + ', '.join('U+%04X' % cp for cp in missing))

    def test_committed_pack_header_matches_the_ttf(self):
        if not PACK.exists():
            self.skipTest('build/emoji.dat is generated by generate_emoji_pack.py')
        blob = PACK.read_bytes()
        ttf = TTF.read_bytes()
        magic, version, ttf_size, crc = struct.unpack('<4sB3xII16x', blob[:32])
        self.assertEqual(magic, b'EMJ1')
        self.assertEqual(version, 1)
        self.assertEqual(ttf_size, len(ttf))
        self.assertEqual(crc, zlib.crc32(ttf) & 0xFFFFFFFF)
        self.assertEqual(blob[32:], ttf)


if __name__ == '__main__':
    unittest.main()
