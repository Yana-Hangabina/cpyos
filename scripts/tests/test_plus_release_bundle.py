#!/usr/bin/env python3
"""Gate for the Plus data-pack bundle: target-scoped names + digest truth.

The defect this locks down (0.8.3): both device jobs published their data packs
into one release under the manifest's plain build names.  i18n_pack.dat and
web_pack.dat differ between the targets (same size, different bytes), so the
release shipped one target's i18n and the other's web pack.  A hash-checking
installer refuses; an installer without verification writes the wrong bytes and
the device falls back to English / a web recovery page.

Three properties, each with a mutation that must turn the suite red:

  1. every Plus pack is published as ``plus-<build name>``, so no Plus asset can
     share a name with a Read Pico asset -- even for packs that diverge later;
  2. the staged manifest names the staged files (flash_plus_data.py and
     build_cpyos_site.py both take the last column's basename);
  3. a blob that does not match the manifest's size/SHA-256 refuses the bundle --
     that is the "packs from different targets" case, and it must stop the job
     instead of shipping.

Run: python3 -m unittest scripts.tests.test_plus_release_bundle -v
"""
from __future__ import annotations

import hashlib
import importlib.util
import pathlib
import tempfile
import unittest

import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "scripts"))
import plus_release_bundle as bundle  # noqa: E402


def load_flasher():
    """The device-side flasher, imported from its real file (it is not a package)."""
    path = REPO / "ports" / "metalio_plus" / "scripts" / "flash_plus_data.py"
    spec = importlib.util.spec_from_file_location("flash_plus_data", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def write_tree(root: pathlib.Path, blobs: dict[str, bytes]) -> pathlib.Path:
    """A miniature repo: build/<blob> files plus a manifest naming them."""
    build = root / "build"
    build.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by scripts/generate_data_manifest.py -- do not edit.",
        "partition\tspiffs\t0x00cd0000\t0x00320000",
        "reserved\t0x00080000\t12\tfactory bytes of unknown purpose; never write here",
    ]
    offset = 0
    for role, (name, data) in blobs.items():
        (build / name).write_bytes(data)
        lines.append(f"data\t{role}\t0x{offset:08x}\t0x{0xcd0000 + offset:08x}\t"
                     f"{len(data)}\t{sha(data)}\tbuild/{name}")
        offset += 0x1000
    manifest = build / "data_manifest_plus.txt"
    manifest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return manifest


class PlusReleaseBundleTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = pathlib.Path(self.tmp.name)
        self.manifest = write_tree(self.root, {
            "pinyin": ("pinyin.dat", b"P" * 349),
            "web": ("web_pack.dat", b"W" * 124),
            "i18n": ("i18n_pack.dat", b"I" * 354),
        })
        self.out = self.root / "dist"

    def tearDown(self):
        self.tmp.cleanup()

    def test_every_pack_is_published_under_a_plus_name(self):
        staged = bundle.bundle(self.manifest, self.out, self.root)
        names = sorted(path.name for path in staged)
        self.assertEqual(names, ["plus-i18n_pack.dat", "plus-pinyin.dat", "plus-web_pack.dat"])
        for plain in ("i18n_pack.dat", "web_pack.dat", "pinyin.dat"):
            self.assertFalse((self.out / plain).exists(), f"{plain} must not be staged under its plain name")
        for path in staged:
            self.assertEqual(sha(path.read_bytes()), sha(next(
                (self.root / "build" / n).read_bytes()
                for n in ("pinyin.dat", "web_pack.dat", "i18n_pack.dat") if path.name == "plus-" + n)))

    def test_published_names_cannot_collide_with_readpico_names(self):
        readpico = ["pinyin.dat", "web_pack.dat", "i18n_pack.dat", "cjk_core_3500.dat"]
        plus = [bundle.published_name(name) for name in readpico]
        self.assertEqual(bundle.collisions(readpico, plus), [],
                         "the Plus names must be disjoint from the Read Pico names")
        # Mutation: without the prefix the two releases collide on every pack --
        # this is what 0.8.3 shipped.
        self.assertEqual(bundle.collisions(readpico, [bundle.published_name(n, "") for n in readpico]),
                         sorted(readpico), "the check itself must notice plain names")

    def test_staged_manifest_names_the_staged_files(self):
        bundle.bundle(self.manifest, self.out, self.root)
        staged_manifest = self.out / "data_manifest_plus.txt"
        rows = [line.split("\t") for line in
                staged_manifest.read_text(encoding="utf-8").splitlines() if line.startswith("data\t")]
        self.assertEqual(len(rows), 3)
        # The last column is a bundle-relative name: the site generator takes its
        # basename inside the release dir, the flasher resolves it next to the manifest.
        self.assertEqual([row[6] for row in rows],
                         ["plus-pinyin.dat", "plus-web_pack.dat", "plus-i18n_pack.dat"])
        flasher = load_flasher()
        _, _, parsed = flasher.parse_manifest(str(staged_manifest))
        for row in parsed:
            self.assertTrue(row["path"].startswith(str(self.out) + "/"),
                            f"{row['name']} must resolve inside the bundle, got {row['path']}")
            self.assertTrue(pathlib.Path(row["path"]).name.startswith("plus-"))
            self.assertEqual(flasher.sha256(row["path"]), row["sha256"])

    def test_pack_that_does_not_match_its_digest_stops_the_bundle(self):
        """The 0.8.3 shape: this tree holds the other target's pack."""
        # Same size, different bytes -- exactly how the two i18n packs differ.
        (self.root / "build" / "i18n_pack.dat").write_bytes(b"X" * 354)
        with self.assertRaises(SystemExit) as caught:
            bundle.bundle(self.manifest, self.out, self.root)
        message = str(caught.exception)
        self.assertIn("i18n", message)
        self.assertIn("hashes", message)
        self.assertFalse((self.out / "plus-i18n_pack.dat").exists(), "nothing may be staged on refusal")

    def test_size_mismatch_is_named_as_such(self):
        (self.root / "build" / "web_pack.dat").write_bytes(b"W" * 123)
        with self.assertRaises(SystemExit) as caught:
            bundle.bundle(self.manifest, self.out, self.root)
        self.assertIn("web", str(caught.exception))
        self.assertIn("is 123 B but the manifest says 124 B", str(caught.exception))

    def test_real_tree_manifest_agrees_with_the_files(self):
        """Integration: when this checkout has a Plus build, the repo's own Plus
        manifest must describe the blobs in build/.  This is the check that would
        have failed while the 0.8.3 asset set was being assembled.

        Skipped in a Read Pico checkout (no Plus pack in ports/metalio_plus): the
        manifest there is left over from an earlier Plus build and its i18n pack is
        the Read Pico one -- which is exactly the mixing this gate refuses.
        """
        manifest = REPO / "build" / "data_manifest_plus.txt"
        plus_pack = REPO / "ports" / "metalio_plus" / "build_shell" / "i18n_pack.dat"
        if not manifest.is_file() or not plus_pack.is_file():
            self.skipTest("no Plus build in this checkout; the Plus manifest here is not authoritative")
        checked = bundle.check_sources(manifest, REPO)
        self.assertGreaterEqual(len(checked), 4, "the Plus manifest should list all data packs")


if __name__ == "__main__":
    unittest.main(verbosity=2)
