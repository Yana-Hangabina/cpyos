#!/usr/bin/env python3
"""
Generate I18n C++ files from per-language YAML translations.

Reads YAML files from a translations directory (one file per language) and generates:
- I18nKeys.h:     Language enum, StrId enum, helper functions
- I18nStrings.h:  String array declarations
- I18nStrings.cpp: String array definitions with all translations

Each YAML file must contain:
  _language_name: "Native Name"     (e.g. "Español")
  _language_code: "ENUM_NAME"       (e.g. "ES")
  _order: "N"                       (e.g. "1"; historical metadata, unused)
  _bcp47: "tag"                     (e.g. "es"; drives Language enum order)
  STR_KEY: "translation text"

The English file is the reference. Missing keys in other languages are
automatically filled from English, with a warning.

By default the script scans the src/ and lib/ trees for STR_* references and
reports any translation keys that are never used.  Pass --strip-unused to
omit those keys from the generated output entirely.

Usage:
    python gen_i18n.py [translations_dir [output_dir]] [options]

Examples:
    python gen_i18n.py
    python gen_i18n.py lib/I18n/translations lib/I18n/
    python gen_i18n.py --strip-unused
    python gen_i18n.py --strip-unused --src-dirs src lib/EpdFont
"""

import sys
import os
import re
import struct
import zlib
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple

AUTO_GENERATED_COMMENT = "// THIS FILE IS AUTO-GENERATED BY gen_i18n.py. DO NOT EDIT."
CLANG_FORMAT_OFF_COMMENT = "// clang-format off"
I18N_NAMESPACE_OPEN = "namespace i18n_strings {"
I18N_NAMESPACE_CLOSE = "}  // namespace i18n_strings"
YAML_KEY_RE = re.compile(r'^([A-Za-z_]\w*)\s*:\s*"(.*)"$', flags=re.ASCII)
CPP_IDENTIFIER_RE = re.compile(r"^[A-Za-z_]\w*$", flags=re.ASCII)
STR_KEY_RE = re.compile(r"\bSTR_\w+\b", flags=re.ASCII)

# ---------------------------------------------------------------------------
# Language pack (data partition)
# ---------------------------------------------------------------------------
#
# CROSSPOINT_I18N_PACK builds keep only these languages' strings in the image;
# every other language is read from the pack. ZH_CN stays embedded because it is
# the CJK SKU's default and its glyphs ship in the same image.
I18N_PACK_EMBEDDED_CODES = ("EN", "ZH_CN")
I18N_PACK_MAGIC = b"JILP"
# v2 added contentSignature (offset 36, formerly reserved). Must agree with
# lib/I18n/I18nPackFormat.h; a v1 pack is rejected as "unsupported version".
I18N_PACK_VERSION = 2
I18N_PACK_HEADER_SIZE = 64
I18N_PACK_ENTRY_SIZE = 32
I18N_PACK_MAX_ENTRIES = 64
I18N_PACK_MAX_ENTRY_BYTES = 0x7FFF
I18N_PACK_DEFAULT_PATH = "build/i18n_pack.dat"
# Header: magic, version, headerSize, flags, keyCount, keySignature,
# languageCount, entrySize, indexOffset, indexCrc32, headerCrc32, totalSize,
# contentSignature, reserved[24].  Must agree with lib/I18n/I18nPackFormat.h.
PACK_HEADER_STRUCT = struct.Struct("<4sBBHIIHHIIIII24s")
PACK_HEADER_CRC_OFFSET = 28
# Entry: langId, flags, blobOff, blobSize, blobCrc32, bitmapOff, bitmapSize,
# bitmapCrc32, reserved.  Must agree with lib/I18n/I18nPackFormat.h.
PACK_ENTRY_STRUCT = struct.Struct("<HHIIIIIII")
assert PACK_HEADER_STRUCT.size == I18N_PACK_HEADER_SIZE
assert PACK_ENTRY_STRUCT.size == I18N_PACK_ENTRY_SIZE


class LanguageTable:
    """One language's flat blob, offset table and same-as-English bits.

    ``blob`` is the exact byte sequence the C++ ``STRINGS_<code>_DATA`` array
    holds (UTF-8 strings, each followed by its NUL), so the pack generator can
    reuse it without re-deriving the layout.  English has no bitmap (``bits`` is
    None).
    """

    __slots__ = ("code", "blob", "size", "offsets", "bits", "blob_strings")

    def __init__(self, code: str, blob: bytes, size: int, offsets: List[int],
                 bits: Optional[List[int]], blob_strings: List[str]) -> None:
        self.code = code
        self.blob = blob
        self.size = size
        self.offsets = offsets
        self.bits = bits
        self.blob_strings = blob_strings


def fnv1a32(keys: List[str]) -> int:
    """FNV-1a over each key name plus its NUL, in StrId order.

    I18nPack refuses a pack whose fingerprint differs: offsets built from a
    different key set would read the wrong strings, which is worse than an
    English fallback.
    """
    value = 0x811C9DC5
    for key in keys:
        for byte in key.encode("ascii") + b"\x00":
            value ^= byte
            value = (value * 0x01000193) & 0xFFFFFFFF
    return value


def content_signature(languages: List[str], string_keys: List[str],
                      translations: Dict[str, List[str]]) -> int:
    """FNV-1a over every translation value, key order then language order.

    ``translations[key]`` is indexed by the ``languages`` order, and each value
    is followed by its NUL, so this is the concatenation of every language's
    full (non-deduplicated) string sequence. The firmware bakes the same number
    into ``I18N_CONTENT_SIGNATURE``; a pack rebuilt from edited text with an
    unchanged key set therefore fails validation instead of serving stale
    strings. Missing translations were already filled from English by
    ``load_translations``, so both sides hash the same bytes.
    """
    value = 0x811C9DC5
    for key in string_keys:
        row = translations[key]
        if len(row) != len(languages):
            raise ValueError(f"'{key}' has {len(row)} translations for {len(languages)} languages")
        for text in row:
            for byte in text.encode("utf-8") + b"\x00":
                value ^= byte
                value = (value * 0x01000193) & 0xFFFFFFFF
    return value


def build_language_tables(languages: List[str], string_keys: List[str],
                          translations: Dict[str, List[str]],
                          compiled: Optional[Set[str]] = None) -> Dict[str, LanguageTable]:
    """Build every language's blob/offsets/bitmap exactly as the C++ arrays do."""
    en_strings = [translations[key][0] for key in string_keys]
    en_offsets: List[int] = []
    en_cursor = 0
    for text in en_strings:
        en_offsets.append(en_cursor)
        en_cursor += len(text.encode("utf-8")) + 1
    if en_cursor > 0x7FFF:
        raise ValueError(
            f"Language EN: blob size ({en_cursor} bytes) exceeds 15-bit offset limit (32767)"
        )

    tables: Dict[str, LanguageTable] = {}
    for lang_idx, code in enumerate(languages):
        if compiled is not None and code not in compiled:
            tables[code] = LanguageTable(code, b"", 0, [], [], [])
            continue
        if lang_idx == 0:
            blob = b"".join(text.encode("utf-8") + b"\x00" for text in en_strings)
            tables[code] = LanguageTable(code, blob, len(blob), list(en_offsets), None,
                                         list(en_strings))
            continue

        offsets: List[int] = []
        bits: List[int] = []
        parts: List[bytes] = []
        blob_strings: List[str] = []
        cursor = 0
        for i, text in enumerate(translations[key][lang_idx] for key in string_keys):
            if text == en_strings[i]:
                offsets.append(en_offsets[i] | 0x8000)
                bits.append(1)
            else:
                offsets.append(cursor)
                bits.append(0)
                encoded = text.encode("utf-8") + b"\x00"
                parts.append(encoded)
                blob_strings.append(text)
                cursor += len(encoded)
        if cursor > 0x7FFF:
            raise ValueError(
                f"Language {code}: blob size ({cursor} bytes) exceeds 15-bit offset limit (32767)"
            )
        tables[code] = LanguageTable(code, b"".join(parts), cursor, offsets, bits,
                                     blob_strings)
    return tables


def bitmap_bytes(bits: List[int]) -> bytes:
    """Pack same-as-English bits, LSB-first within each byte (I18nOffsetBuilder.h)."""
    out = bytearray((len(bits) + 7) // 8)
    for index, bit in enumerate(bits):
        if bit:
            out[index >> 3] |= 1 << (index & 7)
    return bytes(out)


def _align4(value: int) -> int:
    return (value + 3) & ~3


def build_pack_bytes(languages: List[str], string_keys: List[str],
                     translations: Dict[str, List[str]]) -> bytes:
    """Serialize every non-embedded language into the data-partition pack.

    Every language in the translation set is included, not only the ones the
    current `custom_i18n_builtin_langs` keeps: that makes the pack independent
    of the build subset, and `--pack-only` can reproduce it byte for byte from
    the same YAML without knowing the subset.
    """
    tables = build_language_tables(languages, string_keys, translations)
    packed = [code for code in languages if code not in I18N_PACK_EMBEDDED_CODES]
    if not packed:
        raise ValueError("no languages to pack: every language is embedded")
    if len(packed) > I18N_PACK_MAX_ENTRIES:
        raise ValueError(f"{len(packed)} packed languages exceeds the format's {I18N_PACK_MAX_ENTRIES}")

    index_size = len(packed) * I18N_PACK_ENTRY_SIZE
    cursor = _align4(I18N_PACK_HEADER_SIZE + index_size)
    body = bytearray()
    body_base = I18N_PACK_HEADER_SIZE + index_size
    index = bytearray(index_size)
    seen: Set[int] = set()

    for position, code in enumerate(packed):
        table = tables[code]
        lang_id = languages.index(code)
        if lang_id in seen:
            raise ValueError(f"duplicate language id {lang_id} in the pack")
        seen.add(lang_id)
        if table.size > I18N_PACK_MAX_ENTRY_BYTES:
            raise ValueError(f"{code}: {table.size} bytes exceeds the 15-bit offset limit")

        # Every region starts on a 4-byte boundary; a bitmap is 189 bytes, so
        # the next blob would otherwise start unaligned.
        blob_off = _align4(cursor)
        body.extend(b"\x00" * (blob_off - (body_base + len(body))))
        body.extend(table.blob)
        cursor = blob_off + table.size

        bitmap = bitmap_bytes(table.bits or [])
        bitmap_off = _align4(cursor)
        body.extend(b"\x00" * (bitmap_off - (body_base + len(body))))
        body.extend(bitmap)
        cursor = bitmap_off + len(bitmap)

        PACK_ENTRY_STRUCT.pack_into(
            index, position * I18N_PACK_ENTRY_SIZE,
            lang_id, 0,
            blob_off, table.size, zlib.crc32(table.blob) & 0xFFFFFFFF,
            bitmap_off, len(bitmap), zlib.crc32(bitmap) & 0xFFFFFFFF,
            0,
        )

    total_size = cursor
    header_zero = PACK_HEADER_STRUCT.pack(
        I18N_PACK_MAGIC, I18N_PACK_VERSION, I18N_PACK_HEADER_SIZE, 0,
        len(string_keys), fnv1a32(string_keys),
        len(packed), I18N_PACK_ENTRY_SIZE, I18N_PACK_HEADER_SIZE,
        zlib.crc32(index) & 0xFFFFFFFF, 0, total_size,
        content_signature(languages, string_keys, translations),
        b"\x00" * 24,
    )
    header_crc = zlib.crc32(header_zero) & 0xFFFFFFFF
    header = bytearray(header_zero)
    # magic(4) version(1) headerSize(1) flags(2) keyCount(4) keySignature(4)
    # languageCount(2) entrySize(2) indexOffset(4) indexCrc32(4) -> headerCrc32
    struct.pack_into("<I", header, PACK_HEADER_CRC_OFFSET, header_crc)

    return bytes(header) + bytes(index) + bytes(body)


def default_pack_path() -> str:
    """<repo>/build/i18n_pack.dat, independent of the process working directory.

    Derived from this script's own location rather than from output_dir so a
    --pack-only run from anywhere still lands next to build/data_manifest.txt.
    SCons executes this file as a pre-script without defining __file__, so fall
    back to the project root (the process cwd there); the Import branch below
    passes $PROJECT_DIR explicitly, which is the authoritative form.
    """
    script = globals().get("__file__")
    root = Path(script).resolve().parent.parent if script else Path.cwd()
    return str(root / I18N_PACK_DEFAULT_PATH)


def parse_generated_layout(header_path: str) -> Tuple[List[str], List[str], int]:
    """Read the StrId order, Language enum and content signature from I18nKeys.h.

    Used by --pack-only so the pack can be rebuilt from the header the firmware
    was actually built with, even after I18nStrings.cpp has been regenerated or
    removed from the command line. The content signature is only compared, to
    warn when the YAML has moved on since that firmware was built.
    """
    text = Path(header_path).read_text(encoding="utf-8")
    strid = re.search(r"enum class StrId : uint16_t \{(.*?)\n\};", text, re.S)
    if not strid:
        raise ValueError(f"{header_path}: cannot find the StrId enum")
    keys = re.findall(r"^\s*(STR_[A-Za-z0-9_]+),", strid.group(1), flags=re.M)
    language = re.search(r"enum class Language : uint8_t \{(.*?)\n\};", text, re.S)
    if not language:
        raise ValueError(f"{header_path}: cannot find the Language enum")
    codes = re.findall(r"^\s*([A-Z][A-Z0-9_]*)\s*=\s*\d+,", language.group(1), flags=re.M)
    if not keys or not codes:
        raise ValueError(f"{header_path}: empty StrId or Language enum")
    signature = re.search(r"I18N_CONTENT_SIGNATURE\s*=\s*0x([0-9A-Fa-f]{8})u", text)
    if not signature:
        raise ValueError(
            f"{header_path}: no I18N_CONTENT_SIGNATURE; regenerate the i18n headers"
        )
    return codes, keys, int(signature.group(1), 16)


# ---------------------------------------------------------------------------
# YAML file reading (simple key: "value" format, no PyYAML dependency)
# ---------------------------------------------------------------------------


def _unescape_yaml_value(raw: str, filepath: str = "", line_num: int = 0) -> str:
    """
    Process escape sequences in a YAML value string.

    Recognized escapes:  \\\\  →  \\       \\"  →  "       \\n  →  newline
    """
    result: List[str] = []
    i = 0
    while i < len(raw):
        if raw[i] == "\\" and i + 1 < len(raw):
            nxt = raw[i + 1]
            if nxt == "\\":
                result.append("\\")
            elif nxt == '"':
                result.append('"')
            elif nxt == "n":
                result.append("\n")
            else:
                raise ValueError(f"{filepath}:{line_num}: unknown escape '\\{nxt}'")
            i += 2
        else:
            result.append(raw[i])
            i += 1
    return "".join(result)


def parse_yaml_file(filepath: str) -> Dict[str, str]:
    """
    Parse a simple YAML file of the form:
        key: "value"

    Only supports flat key-value pairs with quoted string values.
    Aborts on formatting errors.
    """
    result = {}
    with open(filepath, "r", encoding="utf-8") as f:
        for line_num, raw_line in enumerate(f, start=1):
            line = raw_line.rstrip("\n\r")

            if not line.strip():
                continue

            match = YAML_KEY_RE.match(line)
            if not match:
                raise ValueError(
                    f"{filepath}:{line_num}: bad format: {line!r}\n"
                    f'  Expected:  KEY: "value"'
                )

            key = match.group(1)
            raw_value = match.group(2)

            # Un-escape: process character by character to handle
            # \\, \", and \n sequences correctly
            value = _unescape_yaml_value(raw_value, filepath, line_num)

            if key in result:
                raise ValueError(f"{filepath}:{line_num}: duplicate key '{key}'")

            result[key] = value

    return result


# ---------------------------------------------------------------------------
# Load all languages from a directory of YAML files
# ---------------------------------------------------------------------------


def load_translations(
    translations_dir: str,
    verbose: bool = False,
    only_languages: Optional[Set[str]] = None,
) -> Tuple[List[str], List[str], List[str], List[str], Dict[str, List[str]], List[Set[str]]]:
    """
    Read every YAML file in *translations_dir* and return:
        language_codes   e.g. ["EN", "ES", ...]
        language_names   e.g. ["English", "Español", ...]
        language_bcp47   e.g. ["en", "es", ...]
        string_keys      ordered list of STR_* keys (from English)
        translations     {key: [translation_per_language]}

    English is always first; the rest are sorted by _bcp47.

    When *only_languages* is provided, keep only files whose _language_code
    appears in the set (case-insensitive). English is always retained as the
    fallback source.
    """
    yaml_dir = Path(translations_dir)
    if not yaml_dir.is_dir():
        raise FileNotFoundError(f"Translations directory not found: {translations_dir}")

    yaml_files = sorted(yaml_dir.glob("*.yaml"))
    if not yaml_files:
        raise FileNotFoundError(f"No .yaml files found in {translations_dir}")

    # Parse every file
    parsed: Dict[str, Dict[str, str]] = {}
    for yf in yaml_files:
        parsed[yf.name] = parse_yaml_file(str(yf))

    # Apply --only-languages filter (always keep English as the fallback source)
    if only_languages is not None:
        wanted = {code.upper() for code in only_languages} | {"EN"}
        filtered: Dict[str, Dict[str, str]] = {}
        for name, data in parsed.items():
            code = data.get("_language_code", "").upper()
            if code in wanted:
                filtered[name] = data
        missing = wanted - {data.get("_language_code", "").upper() for data in filtered.values()}
        if missing:
            raise ValueError(
                f"--only-languages requested codes {sorted(missing)} but no matching YAML file found"
            )
        parsed = filtered

    # Identify the English file (must exist)
    english_file = None
    for name, data in parsed.items():
        if data.get("_language_code", "").upper() == "EN":
            english_file = name
            break

    if english_file is None:
        raise ValueError("No YAML file with _language_code: EN found")

    for fname, data in parsed.items():
        if not data.get("_bcp47"):
            raise ValueError(f"{fname}: missing _bcp47")

    def _check_unique(field: str) -> None:
        """Raise if any two files share the same value for *field* (e.g. "_order", "_bcp47")."""
        files_by_value: Dict[str, List[str]] = {}
        for fname, data in parsed.items():
            value = data.get(field)
            if not value:
                continue
            files_by_value.setdefault(value, []).append(fname)

        duplicates = {value: sorted(files) for value, files in files_by_value.items() if len(files) > 1}
        if duplicates:
            duplicate_messages = [
                f"{field} {value}: {', '.join(files)}" for value, files in sorted(duplicates.items())
            ]
            raise ValueError(
                f"Duplicate {field} values found:\n  "
                + "\n  ".join(duplicate_messages)
                + f"\nEach {field} value must be unique to ensure a deterministic language order."
            )

    _check_unique("_order")
    _check_unique("_bcp47")

    # Order: English first (enum value 0), then by _bcp47 tag alphabetically.
    # This assigns the Language enum ordinal and also drives the visible
    # Settings menu order (see SORTED_LANGUAGE_INDICES). It has no effect on
    # stored user preferences, since settings.json persists the
    # _language_code string, not the ordinal. _order is retained as metadata
    # and still validated for uniqueness, but no longer drives enum assignment.
    def sort_key(fname: str) -> Tuple[int, str]:
        """English always first (0), then by BCP47 tag."""
        if fname == english_file:
            return (0, "")
        return (1, parsed[fname]["_bcp47"])

    ordered_files = sorted(parsed, key=sort_key)

    # Extract metadata
    language_codes: List[str] = []
    language_names: List[str] = []
    language_bcp47: List[str] = []
    for fname in ordered_files:
        data = parsed[fname]
        code = data.get("_language_code")
        name = data.get("_language_name")
        if not code or not name:
            raise ValueError(f"{fname}: missing _language_code or _language_name")
        language_codes.append(code)
        language_names.append(name)
        language_bcp47.append(data["_bcp47"])

    # String keys come from English (order matters)
    english_data = parsed[english_file]
    string_keys = [k for k in english_data if not k.startswith("_")]

    # Validate all keys are valid C++ identifiers
    for key in string_keys:
        if not CPP_IDENTIFIER_RE.match(key):
            raise ValueError(f"Invalid C++ identifier in English file: '{key}'")

    # Build translations dict, filling missing keys from English
    inherited_sets: List[Set[str]] = [set() for _ in ordered_files]
    translations: Dict[str, List[str]] = {}
    for key in string_keys:
        row: List[str] = []
        for lang_idx, fname in enumerate(ordered_files):
            data = parsed[fname]
            value = data.get(key, "")
            if not value.strip() and fname != english_file:
                value = english_data[key]
                inherited_sets[lang_idx].add(key)
                if verbose:
                    print(
                        f"  INFO: '{key}' missing in {language_codes[lang_idx]}, using English fallback"
                    )
            row.append(value)
        translations[key] = row

    # Warn about extra keys in non-English files
    for fname in ordered_files:
        if fname == english_file:
            continue
        data = parsed[fname]
        extra = [k for k in data if not k.startswith("_") and k not in english_data]
        if extra:
            lang_code = data.get("_language_code", fname)
            if verbose:
                print(
                    f"  WARNING: {lang_code} has keys not in English: {', '.join(extra)}"
                )

    if verbose:
        print(f"Loaded {len(language_codes)} languages, {len(string_keys)} string keys")
    return language_codes, language_names, language_bcp47, string_keys, translations, inherited_sets


# ---------------------------------------------------------------------------
# Unused-string detection
# ---------------------------------------------------------------------------

_GENERATED_FILENAMES: Set[str] = {"I18nKeys.h", "I18nStrings.h", "I18nStrings.cpp"}


def find_used_string_keys(
    src_dirs: List[str],
    skip_filenames: Optional[Set[str]] = None,
) -> Set[str]:
    """
    Scan C/C++ source files under *src_dirs* for STR_* identifiers.

    Files whose basename appears in *skip_filenames* are skipped so that
    the generated I18n files don't count as "usage" of themselves.

    Returns the set of all STR_KEY names that appear at least once.
    """
    if skip_filenames is None:
        skip_filenames = _GENERATED_FILENAMES

    used: Set[str] = set()

    for src_dir in src_dirs:
        p = Path(src_dir)
        if not p.is_dir():
            continue
        for f in p.rglob("*"):
            if f.suffix not in {".cpp", ".h", ".c"}:
                continue
            if f.name in skip_filenames:
                continue
            try:
                text = f.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            for m in STR_KEY_RE.finditer(text):
                used.add(m.group(0))

    return used


def report_unused_keys(
    string_keys: List[str],
    used_keys: Set[str],
) -> List[str]:
    """Return a sorted list of keys from *string_keys* absent in *used_keys*."""
    return [k for k in sorted(string_keys) if k not in used_keys]


# ---------------------------------------------------------------------------
# C++ string escaping
# ---------------------------------------------------------------------------


def escape_cpp_string(s: str) -> List[str]:
    r"""
    Convert *s* into one or more C++ string literal segments.

    Non-ASCII characters are emitted as \xNN hex sequences. After each
    hex escape a new segment is started so the compiler doesn't merge
    subsequent hex digits into the escape.

    Returns a list of string segments (without quotes). For simple ASCII
    strings this is a single-element list.
    """
    if not s:
        return [""]

    s = s.replace("\n", "\\n")

    # Build a flat list of "tokens", where each token is either a regular
    # character sequence or a hex escape.  A segment break happens after
    # every hex escape.
    segments: List[str] = []
    current: List[str] = []
    i = 0

    def _flush() -> None:
        segments.append("".join(current))
        current.clear()

    while i < len(s):
        ch = s[i]

        if ch == "\\" and i + 1 < len(s):
            nxt = s[i + 1]
            if nxt in 'ntr"\\':
                current.append(ch + nxt)
                i += 2
            elif nxt == "x" and i + 3 < len(s):
                current.append(s[i : i + 4])
                _flush()  # segment break after hex
                i += 4
            else:
                current.append("\\\\")
                i += 1
        elif ch == '"':
            current.append('\\"')
            i += 1
        elif ord(ch) < 128:
            current.append(ch)
            i += 1
        else:
            for byte in ch.encode("utf-8"):
                current.append(f"\\x{byte:02X}")
                _flush()  # segment break after hex
            i += 1

    # Flush remaining content
    _flush()

    return segments


def format_cpp_string_literal(segments: List[str], indent: str = "    ") -> List[str]:
    """
    Format string segments (from escape_cpp_string) as indented C++ string
    literal lines, each wrapped in quotes.
    Also wraps long segments to respect ~120 column limit.
    """
    # Effective limit for content: 120 - 4 (indent) - 2 (quotes) - 1 (comma/safety) = 113
    # Using 113 to match clang-format exactly (120 - 4 - 2 - 1)
    MAX_CONTENT_LEN = 113

    lines: List[str] = []

    for seg in segments:
        # Short segment (e.g. hex escape or short text)
        if len(seg) <= MAX_CONTENT_LEN:
            lines.append(f'{indent}"{seg}"')
            continue

        # Long segment - wrap it
        current = seg
        while len(current) > MAX_CONTENT_LEN:
            # Find best split point
            # Scan forward to find last space <= MAX_CONTENT_LEN
            last_space = -1
            idx = 0
            while idx <= MAX_CONTENT_LEN and idx < len(current):
                if current[idx] == " ":
                    last_space = idx

                # Handle escapes to step correctly
                if current[idx] == "\\":
                    idx += 2
                else:
                    idx += 1

            # If we found a space, split after it
            if last_space != -1:
                # Include the space in the first line
                split_point = last_space + 1
                lines.append(f'{indent}"{current[:split_point]}"')
                current = current[split_point:]
            else:
                # No space, forced break at MAX_CONTENT_LEN (or slightly less)
                cut_at = MAX_CONTENT_LEN
                # Don't cut in the middle of an escape sequence
                if current[cut_at - 1] == "\\":
                    cut_at -= 1

                lines.append(f'{indent}"{current[:cut_at]}"')
                current = current[cut_at:]

        if current:
            lines.append(f'{indent}"{current}"')

    return lines


