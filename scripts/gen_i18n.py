def _print_language_table(
    language_codes: List[str],
    language_names: List[str],
    language_bcp47: List[str],
    inherited_sets: List[Set[str]],
    string_keys: List[str],
    unused_keys: Set[str],
    data_sizes: List[int],
) -> None:
    """Print a per-language summary table."""
    total = len(string_keys)
    headers = ("Language", "Code", "BCP47", "Own", "Fallback", "Unused", "Data (B)")

    rows = []
    for code, name, bcp47, inherited, size in zip(
        language_codes, language_names, language_bcp47, inherited_sets, data_sizes
    ):
        own = total - len(inherited)
        fallback = len(inherited)
        # strings this language translated but the code never calls
        unused = len(unused_keys - inherited)
        rows.append((name, code, bcp47, str(own), str(fallback), str(unused), str(size)))

    # EN first, then alphabetically by _bcp47 (matches the Language enum order)
    rows.sort(key=lambda r: (0 if r[1] == "EN" else 1, r[2]))

    col_widths = [len(h) for h in headers]
    for row in rows:
        for i, cell in enumerate(row):
            col_widths[i] = max(col_widths[i], len(cell))

    fmt = "  ".join(f"{{:<{w}}}" for w in col_widths)
    sep = "  ".join("-" * w for w in col_widths)

    def _safe_print(line: str) -> None:
        print(
            line.encode(sys.stdout.encoding or "utf-8", errors="replace").decode(
                sys.stdout.encoding or "utf-8", errors="replace"
            )
        )

    _safe_print(fmt.format(*headers))
    _safe_print(sep)
    for row in rows:
        _safe_print(fmt.format(*row))
    used = total - len(unused_keys)
    dedup_size = sum(data_sizes)
    n_lang = len(rows)
    n_keys = len(string_keys)
    offset_table_size = n_lang * n_keys * 2
    by_code = dict(zip(language_codes, data_sizes))
    embedded_size = sum(by_code.get(code, 0) for code in I18N_PACK_EMBEDDED_CODES)
    packed_codes = [code for code in language_codes if code not in I18N_PACK_EMBEDDED_CODES]
    packed_strings = sum(by_code.get(code, 0) for code in packed_codes)
    bitmap_size = (n_keys + 7) // 8
    bitmap_total = len(packed_codes) * bitmap_size
    # Four alignment pads worst case (blob + bitmap per language) plus header/index.
    pack_estimate = (I18N_PACK_HEADER_SIZE + len(packed_codes) * I18N_PACK_ENTRY_SIZE
                     + packed_strings + bitmap_total + 8 * len(packed_codes))
    print(
        f"\n  Total: {total}  |  Used in code: {used}  |  Never used: {len(unused_keys)}"
    )
    print(
        f"  Flash, every language embedded (C3/simulator): {dedup_size:>7,} B strings"
        f"  +  {offset_table_size:>6,} B offset tables  =  {dedup_size + offset_table_size:>7,} B"
    )
    print(
        f"  Flash, CROSSPOINT_I18N_PACK image (EN+ZH only): {embedded_size:>7,} B strings"
        f"  +  {bitmap_size:>4,} B ZH bitmap  (+ loader code)"
    )
    print(
        f"  Data-partition pack: {len(packed_codes)} languages, {packed_strings:>7,} B strings"
        f"  +  {bitmap_total:>4,} B bitmaps  ~=  {pack_estimate:>7,} B"
    )


def _append_string_data_entry(lines: List[str], text: str) -> None:
    """
    Escape *text*, append a \\0 null separator, and format as indented C++
    string literal lines for inclusion in a flat char data array blob.
    """
    segments = escape_cpp_string(text)
    # Append the null entry separator to the last segment
    if segments and segments[-1] != "":
        segments[-1] += "\\0"
    elif segments:
        segments[-1] = "\\0"
    else:
        segments = ["\\0"]
    lines.extend(format_cpp_string_literal(segments))


def _append_string_entry(lines: List[str], text: str, comment: str = "") -> None:
    """Escape *text*, format as indented C++ lines, append comma (and optional comment)."""
    segments = escape_cpp_string(text)
    formatted = format_cpp_string_literal(segments)
    suffix = f",  // {comment}" if comment else ","
    formatted[-1] += suffix
    lines.extend(formatted)


def _write_file(path: str, lines: List[str], verbose: bool = False) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
        f.write("\n")
    if verbose:
        print(f"Generated: {path}")


def parse_builtin_langs(value: Optional[str], languages: List[str]) -> Optional[Set[str]]:
    """Resolve a comma-separated language list to the set compiled into the firmware.

    None, empty or "all" means every language (returns None). English is always
    included: it is the fallback every other language's offsets point into.
    An unknown code is an error rather than silently dropped, so a typo cannot
    ship a build that is missing a language someone asked for.
    """
    if value is None or value.strip().lower() in ("", "all"):
        return None
    by_upper = {c.upper(): c for c in languages}
    requested = [t.strip().upper() for t in value.split(",") if t.strip()]
    unknown = [t for t in requested if t not in by_upper]
    if unknown:
        raise ValueError(
            f"Unknown language code(s) in built-in list: {', '.join(unknown)}. "
            f"Valid codes: {', '.join(languages)}"
        )
    return {by_upper[t] for t in requested} | {"EN"}


