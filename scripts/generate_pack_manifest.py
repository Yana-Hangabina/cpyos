#!/usr/bin/env python3
"""Build the flat data-pack manifest consumed by device OTA.

Input:  build/data_manifest.txt (generated by generate_data_manifest.py)
Output: build/readpico-packs.txt

One line per blob, in partition order:

    <asset> <partition offset> <size> <sha256> <limit>

`limit` is the next blob's partition offset, or the partition end for the last
one. The device refuses an erase that would run past it, so a corrupt manifest
cannot make the OTA write over the next pack. The OTA updater derives each
asset URL from the release manifest URL; no mirror is baked into this file.

Usage:
  python3 scripts/generate_pack_manifest.py [--repo DIR] [--out FILE] [--check]
"""

from __future__ import annotations

import argparse
import hashlib
import os
import sys
from pathlib import Path

ASSETS = {
    'pinyin': 'pinyin.dat',
    'web': 'web_pack.dat',
    'hyphen': 'hyphen.dat',
    'i18n': 'i18n_pack.dat',
    'emoji': 'emoji.dat',
}


def fail(message: str) -> None:
    print(f'error: {message}', file=sys.stderr)
    raise SystemExit(1)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b''):
            digest.update(chunk)
    return digest.hexdigest()


def render(repo: Path) -> str:
    manifest = repo / 'build' / 'data_manifest.txt'
    if not manifest.is_file():
        fail(f'no {manifest}; run scripts/generate_data_manifest.py first')
    partition_size = None
    rows = []
    for line in manifest.read_text(encoding='utf-8').splitlines():
        if not line or line.startswith('#'):
            continue
        fields = line.split('\t')
        if fields[0] == 'partition' and fields[1] == 'spiffs':
            partition_size = int(fields[3], 0)
        elif fields[0] == 'data' and len(fields) == 7:
            _kind, name, offset, _address, size, digest, relative = fields
            blob = repo / relative
            if not blob.is_file():
                fail(f'{relative} is missing')
            if blob.stat().st_size != int(size) or sha256_file(blob) != digest:
                fail(f'{relative} no longer matches data_manifest.txt')
            if name not in ASSETS:
                fail(f'unknown data pack role {name!r}')
            rows.append({
                'asset': ASSETS[name],
                'offset': int(offset, 0),
                'size': int(size, 0),
                'sha256': digest,
            })
    if partition_size is None:
        fail('data_manifest.txt has no spiffs partition row')
    if not rows:
        fail('data_manifest.txt has no data rows')
    rows.sort(key=lambda row: row['offset'])
    lines = ['# CPYOS data packs v1', '# asset offset size sha256 limit']
    for index, row in enumerate(rows):
        limit = rows[index + 1]['offset'] if index + 1 < len(rows) else partition_size
        if row['offset'] + row['size'] > partition_size or limit < row['offset'] + row['size']:
            fail(f'{row["asset"]} does not fit before its limit')
        lines.append(
            f'{row["asset"]} 0x{row["offset"]:06x} {row["size"]} {row["sha256"]} 0x{limit:06x}'
        )
    return '\n'.join(lines) + '\n'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', default=str(Path(__file__).resolve().parent.parent))
    parser.add_argument('--out', help='default: build/readpico-packs.txt')
    parser.add_argument('--check', action='store_true', help='only verify the output is current')
    args = parser.parse_args()
    repo = Path(args.repo)
    text = render(repo)
    out = Path(args.out) if args.out else repo / 'build' / 'readpico-packs.txt'
    if args.check:
        if not out.is_file() or out.read_text(encoding='utf-8') != text:
            fail(f'{out} is stale; re-run without --check')
        print(f'{out} is current')
        return
    os.makedirs(out.parent, exist_ok=True)
    out.write_text(text, encoding='utf-8')
    print(f'{out}: {len(text.splitlines()) - 2} pack(s)')


if __name__ == '__main__':
    main()
